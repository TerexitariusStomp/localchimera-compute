#!/usr/bin/env bash
# radicle-delegate-setup.sh — one-time setup so a delegate's local Radicle node
# can sync this repo's board to the onion-only production seed over Tor.
#
# Generic & opsec-safe: contains NO secrets and NO server addresses. It reads the
# seed(s) from deploy/radicle-seeds.local.txt, which you create from the
# committed .example template using a value obtained OUT-OF-BAND (vault / secure
# channel) — never from the public repo.
#
# Idempotent. Usage:  tools/dev/radicle-delegate-setup.sh [--timer] [--sleep-hook]
#   --timer       also install a systemd --user timer that runs playnet-sync.sh
#   --sleep-hook  also install a system-sleep hook (needs sudo) that restarts
#                 radicle-node.service after every suspend/resume — the
#                 daemon's Tor/peer sessions die with the network interface on
#                 suspend but the process itself never exits or notices, so
#                 Restart=on-failure can't catch it and pushes/announces fail
#                 silently for as long as the laptop stays up. Root-caused
#                 2026-08-13 after a multi-hour Radicle propagation failure.
set -uo pipefail

REPO_ROOT="$(git -C "$(dirname "${BASH_SOURCE[0]}")" rev-parse --show-toplevel 2>/dev/null)"
[ -n "$REPO_ROOT" ] || REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
SEEDS_FILE="$REPO_ROOT/deploy/radicle-seeds.local.txt"
SYNC="$REPO_ROOT/tools/dev/playnet-sync.sh"

echo "[1/4] Checking prerequisites…"
command -v rad >/dev/null || { echo "  ✗ 'rad' not found on PATH"; exit 1; }
if ! ss -ltn 2>/dev/null | grep -q '127.0.0.1:9050'; then
  echo "  ! Tor SOCKS (127.0.0.1:9050) not detected — install/enable tor before syncing onion seeds."
fi
if [ ! -f "$SEEDS_FILE" ]; then
  echo "  ✗ $SEEDS_FILE missing."
  echo "    cp deploy/radicle-seeds.local.txt.example deploy/radicle-seeds.local.txt"
  echo "    then paste the real seed (obtained out-of-band) into it."
  exit 1
fi

echo "[2/4] Enabling Tor Full Proxy Mode on this node…"
rad config set node.proxy 127.0.0.1:9050 >/dev/null
rad config set node.onion.mode forward    >/dev/null
echo "  ✓ node.proxy=127.0.0.1:9050  node.onion.mode=forward"

echo "[3/4] Wiring the configured seed(s) into node.connect + preferredSeeds…"
python3 - "$SEEDS_FILE" <<'PY'
import json, sys, os
seeds=[]
for ln in open(sys.argv[1]):
    ln=ln.split('#',1)[0].strip()
    if ln: seeds.append(ln)
p=os.path.expanduser("~/.radicle/config.json"); c=json.load(open(p)); n=c["node"]
for key in ("connect",):
    cur=n.setdefault(key,[])
    for s in seeds:
        if s not in cur: cur.append(s)
ps=c.setdefault("preferredSeeds",[])
for s in seeds:
    if s not in ps: ps.append(s)
json.dump(c,open(p,"w"),indent=2)
print(f"  ✓ {len(seeds)} seed(s) wired (node.connect + preferredSeeds)")
PY

echo "    restarting node to apply…"
systemctl --user restart radicle-node.service 2>/dev/null || rad node stop >/dev/null 2>&1 && rad node start >/dev/null 2>&1 || true

WANT_TIMER=; WANT_SLEEP_HOOK=
for arg in "$@"; do
  case "$arg" in
    --timer) WANT_TIMER=1 ;;
    --sleep-hook) WANT_SLEEP_HOOK=1 ;;
  esac
done

if [ -n "$WANT_TIMER" ]; then
  echo "[4/4] Installing systemd --user timer (15-min board sync)…"
  mkdir -p ~/.config/systemd/user
  GUIXBIN="$(dirname "$(command -v rad)")"
  cat > ~/.config/systemd/user/playnet-sync.service <<EOF
[Unit]
Description=Push local Radicle repo state to the playnet seed(s) over tor
After=network-online.target

[Service]
Type=oneshot
WorkingDirectory=$REPO_ROOT
Environment=PATH=$GUIXBIN:/run/current-system/profile/bin:/usr/local/bin:/usr/bin:/bin
ExecStart=$SYNC
EOF
  cat > ~/.config/systemd/user/playnet-sync.timer <<'EOF'
[Unit]
Description=Periodic playnet board sync

[Timer]
OnBootSec=2min
OnUnitActiveSec=15min
Persistent=true

[Install]
WantedBy=timers.target
EOF
  systemctl --user daemon-reload
  systemctl --user enable --now playnet-sync.timer >/dev/null 2>&1
  echo "  ✓ timer enabled (every 15 min)"
else
  echo "[4/4] Skipping timer (pass --timer to install it)."
fi

if [ -n "$WANT_SLEEP_HOOK" ]; then
  echo "[5/5] Installing system-sleep hook (restarts radicle-node.service on resume)…"
  HOOK_SRC="$(mktemp)"
  cat > "$HOOK_SRC" <<'EOF'
#!/bin/sh
# radicle-node-resume — restart the invoking user's radicle-node.service
# after any suspend/hibernate cycle. Generated by
# tools/dev/radicle-delegate-setup.sh --sleep-hook; re-run that to reinstall.
#
# The daemon's TCP/Tor peer sessions die with the network interface on
# suspend, but the process itself never exits or notices: it keeps answering
# RPC calls (rad node status/connect) with stale "connected" state while
# genuinely unable to push/announce over those dead sessions.
# Restart=on-failure in the unit can't catch this because the daemon never
# actually fails. Root-caused 2026-08-13.
set -e

case "$1" in
    post)
        TARGET_USER="__RADICLE_SLEEP_HOOK_USER__"
        TARGET_UID="$(id -u "$TARGET_USER")"
        export XDG_RUNTIME_DIR="/run/user/$TARGET_UID"
        runuser -u "$TARGET_USER" -- systemctl --user restart radicle-node.service
        ;;
esac
EOF
  sed -i "s/__RADICLE_SLEEP_HOOK_USER__/$(id -un)/" "$HOOK_SRC"
  if sudo install -o root -g root -m 0755 "$HOOK_SRC" \
       /usr/lib/systemd/system-sleep/radicle-node-resume; then
    echo "  ✓ installed /usr/lib/systemd/system-sleep/radicle-node-resume"
  else
    echo "  ✗ sudo install failed — run manually:"
    echo "    sudo install -o root -g root -m 0755 $HOOK_SRC /usr/lib/systemd/system-sleep/radicle-node-resume"
  fi
  rm -f "$HOOK_SRC"
else
  echo "[5/5] Skipping sleep hook (pass --sleep-hook to install it; needs sudo)."
fi

echo
echo "Done. Push the board any time with:  tools/dev/playnet-sync.sh"
